"""Streamlit presentation for the CPU-runnable application shell."""

from __future__ import annotations

import plotly.graph_objects as go
import streamlit as st

from .analytics import make_demonstration_figure
from .guidance import get_local_guidance
from .prediction.demo import DemonstrationClassifier
from .prediction.schema import PredictionOutcome


_DEMO_CLASSIFIER = DemonstrationClassifier()


def render_app() -> None:
    st.title("AI-Driven Emotion Detection & Personalized Learning Support")
    st.caption(
        "A text-based learning support prototype. Any future emotion output will be an estimate, "
        "not a reliable reading of a learner's internal state or a diagnosis."
    )

    page = st.sidebar.segmented_control(
        "Page",
        ("Study challenge", "Demonstration analytics"),
        default="Study challenge",
    )
    if page == "Demonstration analytics":
        _render_analytics()
    else:
        _render_study_challenge()


def _render_study_challenge() -> None:
    st.warning(
        "DEMONSTRATION MODE: the scores below are fixed illustrative fixtures. "
        "They do not analyze the words you enter and are not validated model probabilities."
    )
    st.info(
        "Privacy: this shell does not call Gemini or another external AI service. "
        "It does not write your text to a log or file. Please do not enter identifying or sensitive details."
    )

    text = st.text_area(
        "Describe a study challenge",
        placeholder="For example: I am having trouble deciding how to start this assignment.",
        max_chars=2000,
        height=140,
        help=(
            "The fixed demonstration does not analyze your words. Your entry is not sent "
            "to an external service or written to an app file."
        ),
    )

    if st.button("Analyse demonstration", type="primary", width="stretch"):
        try:
            result = _DEMO_CLASSIFIER.predict(text)
        except ValueError as exc:
            st.session_state.pop("demo_result", None)
            st.error(str(exc))
        else:
            st.session_state["demo_result"] = result

    st.markdown("#### Model status")
    st.info(
        "The intended system outputs are Bored, Confident, Confused, Curious, and Frustrated. "
        "No BiLSTM or BERT model is loaded: the same fixed demonstration fixture is shown "
        "for every non-empty entry. Genuine model training is pending suitable, approved "
        "five-label data and the required human reviews. Gemini integration is not part of this shell."
    )

    result = st.session_state.get("demo_result")
    if result is not None:
        st.markdown("#### Illustrative demonstration scores")
        st.caption(
            "These confidence-style values exist only to demonstrate the interface. "
            "They are not calibrated probabilities, predictions, or validated results."
        )
        st.dataframe(
            result.score_rows(),
            hide_index=True,
            alt="Illustrative scores and thresholds for the five emotion categories",
        )
        if result.outcome is PredictionOutcome.NO_CLEAR_CATEGORY:
            st.write("Demonstration outcome: no clear category at the illustrative thresholds.")
        else:
            selected = ", ".join(label.value for label in result.selected_labels)
            st.write(f"Demonstration categories at illustrative thresholds: {selected}")

        st.markdown("#### Local learning guidance")
        st.caption("General suggestions only; not generated by AI or personalized from your text.")
        for tip in get_local_guidance():
            st.markdown(f"- {tip}")

    st.divider()
    st.caption("Interaction logging is off. Submitted text is never included in prediction records.")


def _render_analytics() -> None:
    st.subheader("Demonstration analytics")
    st.warning(
        "All chart values are illustrative fixtures. They do not represent students, "
        "real interactions, model performance, or collected analytics."
    )
    figure: go.Figure = make_demonstration_figure()
    st.plotly_chart(
        figure,
        alt="Illustrative category counts, not real learner activity",
    )

